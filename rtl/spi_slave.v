`timescale 1ns/1ps
`default_nettype none

module spi_slave #(
    parameter WIDTH = 8
) (
    input  wire             rst,   //Asynchronous active high reset
    input  wire             sclk,  // SPI clock generated by master
    input  wire             cpol,  // decides the idle value of Sclk
    input  wire             cpha,  // decides the sampling and launching edge
    input  wire             cs,    // chip select is active low
    input  wire             mosi,  //Master out Slave in
    output wire             miso,  // master in slave out
    output reg  [WIDTH-1:0] rx_data,  //Recieved data
    input  wire [WIDTH-1:0] tx_data,  //Data to transmitt
    output wire             data_valid // indicated completion
);

    localparam CW = $clog2(WIDTH + 1);   //calculates the number of bits needed for the counter to count the bit transmitted
                                         // why Width +1 ? because its needed to count to 0-WIDTH 0-8 for example 
    
    //Width Validation//
    initial begin
    if (WIDTH < 2) begin 
        $display("spi_slave: need WIDTH >= 2"); $finish;
    end
    end


    wire samp_clk  = sclk ^ cpol ^ cpha;       //posedge = sample/receives MOSI and negedge = shifting 
    wire frame_rst = rst | cs;                 // frame start is held in reset while cn = 1 // the recieve and transmitt counters resets whenever SPI frame ends
    

    //receive: shift in on every sample edge until WIDTH bits are in
    /* verilator lint_off UNUSEDSIGNAL */
    reg [WIDTH-1:0] rx_sh;                          // top bit is shifted out unused: rx_data takes {rx_sh[W-2:0], mosi} // temperory shift register
    /* verilator lint_on UNUSEDSIGNAL */          
    reg [CW-1:0]    rbit;                           // number of bits shifted

    //---recieve shift register--- only stores the data in temperory register//

    always @(posedge samp_clk or posedge frame_rst) begin
        //frame_rst = 1 when CS = 1 --> that is it clears the register whenever master deselects slave
        //when frame_rst = 1 ---> it clears the temperory shift register and bit counter
        if (frame_rst) begin
            rx_sh <= {WIDTH{1'b0}};
            rbit  <= {CW{1'b0}};
        end
        // frame_rst = 0 ---> then check number of bits shifted --? it number of bits shifted is not equal to width continue shifting and increaing bit counter
        else if (rbit != WIDTH) begin
            rx_sh <= {rx_sh[WIDTH-2: 0],mosi};
            rbit  <= rbit + 1'b1;
        end
    end



    //---rx_data--- npw we publish data to rx_data only when all the bita have already arrieved//
    reg set_tog;    // toggles after one complete frame -- it changes the frame whenever one complete word is received
    //tiggers on every rising edge of samp_clk and external resets  --- we have not used posedge of frame_rst here cause cs high can also cause frame_rst and we want rx_data to retain its previous value even after the frame ends and it will change only when new value will be added
    always @(posedge samp_clk or posedge rst) begin   
        if (rst) begin
            rx_data <= {WIDTH{1'b0}};
            set_tog <= 1'b0;
        end
        // cs = 0 and number of bits is equal to Width-1 ( if Widht =8 then rbit = 7, cause at rbit = 8 it will stop recieving data anymore)
        else if (!cs && rbit == WIDTH-1) begin
            rx_data <= {rx_sh[WIDTH-2], mosi};
            set_tog <= ~set_tog;                  //Every successfully completed frame toggles this bit.
        end
    end

    

    //---valid data---//
    reg snap;          //stores the value of set_tog when new SPI frame starts
    always @(negedge cs or posedge rst ) begin    // cs = 0(means master is starting a new frame) or external rst is high
        if (rst) begin 
            snap <= 1'b0;    //intialised to zero
        end
        else  begin   
        snap <= set_tog;     // takes the snapshot of set_tog during the start of the frame and then doesn't changes during the frame 
        end
    end
    assign data_valid = (set_tog != snap);

    

    //transmit --- tx_data is latched at fram start,  one bit per shift egde//
    reg [WIDTH-1:0] tx_hold;  // stores snapshot of tx_data at the start of the frame
    always @(negedge cs or posedge rst) begin
        if (rst) tx_hold <= {WIDTH{1'b0}};
        else     tx_hold <= tx_data;
    end


    reg [CW-1:0] t_cnt;   // counter tracks how many bit transfer  have occured
    always @(negedge samp_clk or posedge frame_rst) begin
        if (frame_rst)             t_cnt <= {CW{1'b0}};  // frame_rst = 1 means either cs= 1 ( master deselected slave) or external reset = 1
        else if (t_cnt != WIDTH)   t_cnt <= t_cnt +1'b1;
    end

    

    //here we are deciding when the first bit of miso should be presented (CPHA =0 and CPHA =1 )
    //tidx_raw is used to decide which bit of tx_hold should be sent to miso
    wire [CW-1:0] tidx_raw = cpha ? ((t_cnt == 0) ? {CW{1'b0}} : t_cnt - 1'b1) : t_cnt;
    wire [CW-1:0] tidx     = (tidx_raw > WIDTH - 1) ? (WIDTH - 1) : tidx_raw; 

    assign miso = cs ? 1'b0 : tx_hold[WIDTH-1-tidx];

    
endmodule

`default_nettype wire