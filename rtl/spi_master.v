`timescale 1ns/1ps
`default_nettype none

module spi_master #(
    parameter WIDTH = 8,
    parameter CLK_DIV = 4        // se can decide how many cycles of system clock we need in half cycle of our Sclk period

) (
    input wire               clk,                   // main synchronous clock that controls the master
    input wire               rst,                   // the synchronous active high reset
    input wire               start,                 // starts a new transition
    input wire               cpol,                  // selectes the idle value for clk 
    input wire               cpha,                  // selectes which edge would be the one for sampling the data by slave
    input  wire [WIDTH-1:0]  tx_data,               // parallel input data by master
    output reg [WIDTH-1:0]  rx_data,               // parallel output data by the slave
    output wire              busy,                  // this is indication after start = 1 and we have started transacting data so no other next start could disturb it 
    output reg               done,                  // this is indication of completion of one start cycle
    output reg               sclk,                  // clock generated by the master
    output reg               mosi,                  // master serial output and slave input
    input  wire              miso,                  // master serial in slave out
    output reg               cs                     // chip select when its high we stop the transmittion and when its low out transmittion continues it doesn't toggle during the transmittion 
);


    //---internal counter width calculation---//
    localparam DW = (CLK_DIV > 1) ? $clog2(CLK_DIV) : 1;     // number of bits needed to count the clock divisions in sclk half cycle 
    localparam BW = $clog2(WIDTH) +1;                        // counter for index of transmitted bit-- used to keep the track of which bit should be sent in transition 
    localparam EW = $clog2(2*WIDTH) + 1;                     // Counter for edges  --- one bit requires 2 edges to be transfered 


    //-- parameted Validation --//
    initial begin
        if (WIDTH < 2 || CLK_DIV < 1) begin
            $display("spi_master: need WIDTH >= 2 and CLK_DIV >= 1");
            $finish;
        end
    end


    //-- State-machine Declarations --// 
    localparam [2:0] IDLE      = 3'd0,   // waiting for start; sclk is at idle value which comes from cpol; and cs = 1
                     SETUP     = 3'd1,   // cs = 0, waits one half period ----> one full period befor 1st edge
                     TRANSFER  = 3'd2,   // 2*WIDTH sclk edges
                     HOLD      = 3'd3,   // one half period after the last edge, cs = 0
                     GAP       = 3'd4;   // now cs = 1 for one half period then done
    
    //--internal registers --//
    reg [2:0]    state;                                             // stores the current state of master
    reg [DW-1:0] div_count;                                         //It counts the system clock cycles to decide when the SCLK signal should toggle.
    localparam [31:0] DIV_LAST = CLK_DIV -1;                        //Stores the final count value of the divider.
    wire              tick     = (div_count == DIV_LAST[DW-1:0]);   // one pulse per half sclk period --- When tick becomes high, the master can perform the next clock-edge operation.
    reg               pend;                                         // indicated whether new start request had arrived while master is busy then is becomes hight
    reg [WIDTH-1:0]   pend_data;                                    //stores the data associated with the pending start request this ensures that the correct data is transfered even if tx_data changes later
    reg               cpha_q;                                       // stores the value of CPHA for one frame of transmittion 
    reg [WIDTH-1:0]   tx_frame;                                     // latched parallel input data used by the master for the current frame cause tx_data could be changed during the transmission 
    reg [BW-1:0]      tx_idx;                                       // keep the track of next bit of tx_frame to be launched
    reg [WIDTH-1:0]   rx_shift;                                     // this stores the serial input data from master (MISO) each bit received is shifted in this register to keep the correct sequence of data 
    reg [EW-1:0]      edge_cnt;                                     // count the number of sclk edges generated during one frame



    //-- Start control and busy signal --//
    wire              go = pend | start;
    wire [WIDTH-1:0] load_data = pend ? pend_data : tx_data;
    assign busy = (state != IDLE);


    always @(posedge clk) begin
        done <= 1'b0;                       // idle value of done is Zero
        if (rst) begin
            state     <= IDLE;
            div_count <= {DW{1'b0}};
            //mid-frame reset: raise cs first then sclk returns to idle value one cycle later,
            // so the slave never sees the clock edge coincides with the cs = 1;
            if (!(state == SETUP || state == TRANSFER || state == HOLD || state == GAP)) begin
                sclk       <= cpol;
                mosi       <=  1'b0;
                cs         <= 1'b1;
                rx_data    <= {WIDTH{1'b0}};
                rx_shift   <= {WIDTH{1'b0}};
                tx_frame   <= {WIDTH{1'b0}};
                tx_idx     <= {BW{1'b0}};
                edge_cnt   <= {EW{1'b0}};
                pend       <= 1'b0;
                pend_data  <= {WIDTH{1'b0}};
                cpha_q     <= 1'b0;
            end
        end
//-----when reset is not high-----//
        else begin
                if (start && busy) begin
                    pend       <= 1'b1;
                    pend_data  <= tx_data; // copies tx-data to the pend registor --- thats how it remmembers the pending data
                end

        if (state == IDLE) begin
            div_count <= {DW{1'b0}};
            div_count <= tick ? {DW{1'b0}} : div_count + 1'b1;
        end    

//-----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
        case (state)

        IDLE: begin
            sclk <= cpol;
            if (go) begin
                pend      <= 1'b0;
                cpha_q    <= cpha;
                tx_frame  <= load_data;
                rx_shift  <= {WIDTH{1'b0}};
                edge_cnt  <= {EW{1'b0}};
                cs        <= 1'b0;
                if (!cpha) begin
                    mosi   <= load_data[WIDTH-1];   // msb bit
                    tx_idx <= 1;
                end 
                else begin
                    mosi   <= 1'b0;
                    tx_idx <= 0;
                end
                state <= SETUP;
            end
        end 

//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
        SETUP: if (tick) begin
            state <= TRANSFER;
        end
//--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

        TRANSFER: if (tick) begin
            sclk       = ~sclk;
            edge_cnt   = edge_cnt + 1'b1;

            if (!edge_cnt[0]) begin         // leading edge
                if (!cpha_q) begin          // cpha_q = 0: sampling data
                    rx_shift  <=  {rx_shift[WIDTH-2:0], miso};
                end
                else begin
                    mosi   <= tx_frame[WIDTH-1-tx_idx];
                    tx_idx <= tx_idx + 1'b1;
                end
            end

            else begin                          // trailing edge --- data is launched at the first incoming edge   and sampled next edge                  // cpha = 1 : samples
                if (cpha_q) begin   
                     rx_shift <= {rx_shift[WIDTH-2:0], miso};
                end       
                    else if (edge_cnt != 2*WIDTH -1) begin
                        mosi   <= tx_frame[WIDTH-1-tx_idx];
                        tx_idx <= tx_idx + 1'b1;
                    end
            end

            if (edge_cnt == 2*WIDTH - 1) begin
                state <= HOLD;
            end
        end

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

        HOLD: begin
            if (tick) begin
                cs      = 1'b1;
                rx_data = rx_shift;
                state   = GAP;
            end
        end

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

        GAP: begin
            if (tick) begin
                state <= IDLE;
                done <= 1'b1;
            end
        end

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

            default: state <= IDLE;
        endcase
        end

    end
endmodule


`default_nettype wire